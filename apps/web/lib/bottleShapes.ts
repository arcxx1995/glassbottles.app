// Bottle geometry, in BottleSVG's 80×120 viewBox. Names and Keeper tiers live in
// atelier_pieces; this file only knows how a shape is drawn.
//
// Every shape keeps its cork and the top of its neck at top centre (x 30–50,
// y 16), so the cork, wax drip, pop-off animation and the Shelf's loose cork all
// work with no per-shape code.

export interface BottleShape {
  /** Replaces the classic neck, for long-necked shapes. */
  neck?: string
  /** The glass silhouette. The tint fills this same path. */
  body: string
  /** Line drawing on the glass: fins, petals, faces. */
  details?: string[]
  /** Highlights. */
  shine?: string[]
  /** Where the rolled note sits. */
  note?: { x: number; y: number; w: number; h: number }
}

